#!/usr/bin/env python3
"""Discover the structure of a project and write a draft project map (map.json). Standard library only.

  python3 discover.py <repo>                      print a draft map to stdout
  python3 discover.py <repo> -o map.json          write a draft map
  python3 discover.py <repo> --update map.json    add what is new to an existing map, keep everything you tuned
  python3 discover.py <repo> --check map.json     drift report only (exit 1 when the map is out of date)

What it finds (read-only, no network):
  scripts      tools/, scripts/, bin/ ... and the docstring or first comment of each
  commands     package.json scripts, Makefile and justfile targets
  CI           .github/workflows/*.yml, .gitlab-ci.yml (name, triggers, scripts they call)
  timers       systemd --user timers and crontab lines that reference the repo (Linux)
  agents       skills / agent files in the repo, and user-level skills that mention the repo by name
  hand-overs   folders those skills or timers read and write (task, handoff, review queues ...)
  inputs       data folders the scripts read, external hosts they fetch from
  outputs      files marked "generated by <script>", build folders, releases
  edges        script A mentions script B, a generator writes an output, a skill names another skill ...
Every node carries `source` (the paths it came from); --check compares those with the repo to find drift.
"""
import argparse, fnmatch, glob, json, os, re, subprocess, sys

HOME = os.path.expanduser("~")
FORMAT_VERSION = 1                                         # map.json format; render_map.py refuses newer maps
SKIP_DIRS = {".git", "node_modules", ".venv", "venv", "__pycache__", "dist", "build", ".next", ".cache", "cache",
             "vendor", "target", ".tox", ".mypy_cache", ".pytest_cache", "site-packages", "coverage", ".idea", ".vscode"}
SCRIPT_DIRS = ["tools", "scripts", "script", "bin", "tasks", "ops", "ci", "hack", "devtools"]
SCRIPT_EXT = {".py", ".sh", ".bash", ".js", ".mjs", ".cjs", ".ts", ".rb", ".pl", ".ps1"}
DATA_EXT = {".csv", ".json", ".yaml", ".yml", ".toml", ".tsv", ".xml", ".sql", ".ini"}
FETCH = re.compile(r"urlopen|urllib\.request|requests\.(get|post)|httpx|fetch\(|axios|curl |wget |git clone|ls-remote|aiohttp")
URL = re.compile(r"https?://([A-Za-z0-9.-]+\.[A-Za-z]{2,})")
GEN = re.compile(r"(?i)(?:generated|written|created|produced)\s+(?:automatically\s+)?by\s+[`'\"]?([\w./-]+\.(?:py|sh|js|mjs|ts|rb))")
NOEDIT = re.compile(r"(?i)do not (edit|modify)|@generated")
TEST_HOST = re.compile(r"(^|\.)(test|invalid|example|local|localhost|internal)$|^127\.|^0\.0\.0\.0|^localhost")
CODE_EXT = {".py", ".js", ".mjs", ".ts", ".tsx", ".jsx", ".go", ".rs", ".java", ".kt", ".rb", ".lua", ".c", ".cc", ".cpp", ".h", ".cs", ".swift", ".php", ".vue", ".svelte"}
NOT_MODULE = {"test", "tests", "spec", "docs", "doc", "data", "assets", "static", "public", "examples", "example", "licenses", "logs",
              "config", "website", "site", "fixtures", "migrations", "third_party", "external", "research"} | set(SCRIPT_DIRS)
ENTRY = {"app.py", "main.py", "server.py", "launcher.py", "manage.py", "cli.py", "index.js", "server.js", "main.go", "main.rs", "main.ts", "index.ts"}
DOC_HOSTS = {"github.com/", "docs.", "wikipedia.org", "example.com", "example.org", "localhost", "shields.io", "img.shields.io",
             "opensource.org", "gnu.org", "creativecommons.org", "w3.org", "schema.org", "json-schema.org"}

def rd(p, n=200_000):
    try:
        with open(p, encoding="utf-8", errors="replace") as f: return f.read(n)
    except OSError: return ""
def sh(*a):
    try: return subprocess.run(a, capture_output=True, text=True, timeout=8).stdout
    except (OSError, subprocess.TimeoutExpired): return ""
NEG = re.compile(r"(?i)\b(never|do not|don't|must not|not allowed|forbidden|unless the task)\b")
def positive(txt): return "\n".join(l for l in txt.splitlines() if not NEG.search(l))
def short(s, n): s = " ".join(str(s).split()); return s if len(s) <= n else s[:n - 1].rstrip() + "…"
def slug(s): return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40] or "x"
def tilde(p): return "~" + p[len(HOME):] if p.startswith(HOME + "/") else p

class Map:
    def __init__(self, repo):
        self.repo = os.path.abspath(repo); self.name = os.path.basename(self.repo)
        self.nodes, self.edges = {}, set()
        names = {self.name.lower(), self.name.lower().replace("-", " ").replace("_", " ")}
        self.name_re = re.compile("|".join(re.escape(n) for n in names | {tilde(self.repo).lower(), self.repo.lower()}), re.I)
    def add(self, nid, kind, title, sub="", detail="", source=(), **kw):
        nid = slug(nid); n = self.nodes.get(nid)
        if n:
            n["source"] = sorted(set(n["source"]) | set(source)); return nid
        self.nodes[nid] = {"id": nid, "kind": kind, "title": short(title, 26), "sub": short(sub, 36),
                           "detail": short(detail or sub, 240), "source": sorted(set(source)), **kw}
        return nid
    def link(self, a, b, kind="data"):
        if a and b and a != b and a in self.nodes and b in self.nodes: self.edges.add((a, b, kind))
    def rel(self, p): return os.path.relpath(p, self.repo) if p.startswith(self.repo) else tilde(p)

def tracked(repo):
    out = sh("git", "-C", repo, "ls-files")
    if out: return [os.path.join(repo, l) for l in out.splitlines()]
    files = []
    for root, ds, fs in os.walk(repo):
        ds[:] = [d for d in ds if d not in SKIP_DIRS and not d.startswith(".") or d in (".github", ".agents", ".claude", ".pi")]
        files += [os.path.join(root, f) for f in fs]
    return files

def describe(path):
    """First line of a docstring or of the leading comment block."""
    txt = rd(path, 6000)
    m = re.search(r'^\s*(?:#![^\n]*\n)?(?:\s*#[^\n]*coding[^\n]*\n)?\s*(?:"""|\'\'\')\s*(.+?)(?:"""|\'\'\'|\n\s*\n)', txt, re.S)
    if m: return " ".join(m.group(1).split())
    lines = []
    for l in txt.splitlines()[:25]:
        s = l.strip()
        if s.startswith("#!") or not s: 
            if lines: break
            continue
        if s.startswith(("#", "//", "--")) and not s.startswith("#include"): lines.append(s.lstrip("#/-* ").strip())
        elif s.startswith(("/**", "/*", "*")): lines.append(s.lstrip("/* ").strip())
        else: break
    return " ".join(l for l in lines if l and not l.lower().startswith(("copyright", "spdx", "license", "eslint", "@ts-")))

def scan(repo):
    M = Map(repo); R = M.repo
    files = [f for f in tracked(R) if os.path.isfile(f)]
    relf = {f: os.path.relpath(f, R) for f in files}

    # ---- scripts
    scripts = {}
    for f in files:
        r = relf[f]; parts = r.split(os.sep)
        if any(p in SKIP_DIRS for p in parts[:-1]) or "test" in parts[0].lower(): continue
        ext = os.path.splitext(f)[1]
        top_script = len(parts) == 1 and ext in {".py", ".sh"} and os.access(f, os.X_OK)
        in_dir = len(parts) <= 3 and parts[0] in SCRIPT_DIRS and (ext in SCRIPT_EXT or (not ext and os.access(f, os.X_OK)))
        if (top_script or in_dir) and not parts[-1].startswith(("_", ".")) and parts[-1] not in ("__init__.py", "setup.py", "conftest.py"):
            scripts[f] = M.add("s-" + r, "script", parts[-1], describe(f), source=[r])
    # tests: one node for the test entry point(s)
    tests = [relf[f] for f in files if re.search(r"(^|/)(tests?|spec)(/|$)", relf[f]) and os.path.basename(f) in ("run.py", "run_tests.py", "runtests.py")]
    if tests and not any(relf.get(f) in tests for f in scripts): M.add("tests", "script", "tests", f"test runner ({tests[0]})", source=tests)

    # ---- commands: package.json, Makefile, justfile
    for f in files:
        b = os.path.basename(f); r = relf[f]
        if any(p in SKIP_DIRS for p in r.split(os.sep)): continue
        cmds = {}
        if b == "package.json":
            try: cmds = json.loads(rd(f)).get("scripts") or {}
            except ValueError: pass
            label, run = (f"npm scripts ({os.path.dirname(r)})" if os.path.dirname(r) else "npm scripts"), "npm run"
        elif b in ("Makefile", "makefile", "GNUmakefile"):
            cmds = {m: "" for m in re.findall(r"^([A-Za-z][\w.-]*)\s*:(?!=)", rd(f), re.M) if m not in (".PHONY",)}
            label, run = ("make" + (f" ({os.path.dirname(r)})" if os.path.dirname(r) else "")), "make"
        elif b in ("justfile", "Justfile"):
            cmds = {m: "" for m in re.findall(r"^([A-Za-z][\w-]*)\s*(?:[^:\n]*):", rd(f), re.M)}
            label, run = "just", "just"
        if not cmds: continue
        nid = M.add("c-" + r, "script", label, ", ".join(list(cmds)[:6]) + (" …" if len(cmds) > 6 else ""),
                    f"{run} {' | '.join(f'{k}: {short(v, 50)}' if v else k for k, v in list(cmds.items())[:12])}", source=[r])
        body = " ".join(cmds.values()) + (rd(f) if b != "package.json" else "")
        for sf, sid in scripts.items():
            if re.search(r"(?<![\w-])" + re.escape(os.path.basename(sf)) + r"(?![\w-])", body): M.link(nid, sid, "control")

    # ---- CI
    for f in files:
        r = relf[f]
        if not (re.match(r"\.github/workflows/[^/]+\.ya?ml$", r) or r in (".gitlab-ci.yml", ".circleci/config.yml", "azure-pipelines.yml")): continue
        txt = rd(f); name = (re.search(r"^name:\s*['\"]?(.+?)['\"]?\s*$", txt, re.M) or [None, os.path.basename(r)])[1]
        on = re.search(r"^on:\s*(.*?)(?=^\S)", txt + "\nend:", re.M | re.S)
        trig = sorted(set(re.findall(r"\b(push|pull_request|schedule|workflow_dispatch|release|tags|workflow_call|merge_request)\b", on.group(0) if on else txt)))
        nid = M.add("ci-" + r, "service", name, "CI on " + ", ".join(trig) if trig else "CI pipeline", f"{r}: runs on {', '.join(trig) or '?'}", source=[r])
        for sf, sid in scripts.items():
            if os.path.basename(sf) in txt: M.link(nid, sid, "control")
        if re.search(r"(?i)release|publish|deploy|pages", name) or {"release", "tags"} & set(trig) or re.search(
                r"gh release|action-gh-release|npm publish|twine upload|docker push|push:\s*true|deploy-pages|upload-pages-artifact|cargo publish", txt):
            what = "deploy" if re.search(r"(?i)deploy|pages", txt) else "release"
            oid = M.add(f"o-{what}", "output", "Deploy" if what == "deploy" else "Published release", f"made by {name}", source=[r]); M.link(nid, oid)

    # ---- timers and cron that point at the repo
    ext_texts = {}                                          # text of outside scripts, for edges later
    for unit in re.findall(r"^\s*(\S+)\.timer\b", sh("systemctl", "--user", "list-unit-files", "--type=timer", "--no-legend"), re.M):
        svc = sh("systemctl", "--user", "cat", f"{unit}.service"); tim = sh("systemctl", "--user", "cat", f"{unit}.timer")
        exe = re.findall(r"^ExecStart=[-@+!]*(\S+)(.*)$", svc, re.M)
        texts = svc + "".join(rd(os.path.expanduser(p)) for e in exe for p in [e[0]] + e[1].split() if p.startswith(("/", "~")) and os.path.isfile(os.path.expanduser(p)))
        if not M.name_re.search(texts): continue
        when = " ".join(re.findall(r"^On(?:Calendar|UnitActiveSec|BootSec)=(.+)$", tim, re.M)) or "timer"
        nid = M.add("t-" + unit, "service", unit, f"systemd timer: {short(when, 22)}", f"systemd --user {unit}.timer ({when}) runs {exe[0][0] if exe else '?'}",
                    source=[f"systemd:{unit}"], unit=unit)
        ext_texts[nid] = texts
    for line in sh("crontab", "-l").splitlines():
        if line.strip() and not line.startswith("#") and M.name_re.search(line):
            nid = M.add("cron-" + slug(line[-30:]), "service", "cron job", " ".join(line.split()[:5]), line, source=["cron:" + short(line, 60)])
            ext_texts[nid] = line

    # ---- modules: the application's own code (top-level packages and entry files) and their imports
    mods, mfiles = {}, {}
    for f in files:
        parts = relf[f].split(os.sep); ext = os.path.splitext(f)[1]
        if ext not in CODE_EXT: continue
        if len(parts) == 1 and (parts[0] in ENTRY or (ext == ".py" and "__main__" in rd(f, 20000))) and f not in scripts: key = parts[0]
        elif len(parts) > 1 and parts[0] not in NOT_MODULE and parts[0] not in SKIP_DIRS and not parts[0].startswith(".") and not re.search(r"(^|/)tests?(/|$)", relf[f]): key = parts[0] + "/"
        else: continue
        mfiles.setdefault(key, []).append(f)
    for key, fs in mfiles.items():
        if key.endswith("/") and len(fs) < 3: continue
        exts = sorted({os.path.splitext(x)[1] for x in fs}, key=lambda e: -sum(x.endswith(e) for x in fs))
        readme = next((os.path.join(R, key, r) for r in ("README.md", "readme.md", "__init__.py") if os.path.isfile(os.path.join(R, key, r))), None)
        desc = describe(readme) if readme and readme.endswith(".py") else (re.sub(r"[#*`]", "", next((l for l in rd(readme, 3000).splitlines() if l.strip() and not l.startswith("#")), "")) if readme else "")
        desc = desc if not key.endswith("/") or desc else ""
        mods[key] = M.add("m-" + key, "module", key, f"{len(fs)} {'/'.join(e.lstrip('.') for e in exts[:2])} files" if key.endswith("/") else (describe(fs[0]) or "entry point"),
                          desc or (f"Application code in {key}" if key.endswith("/") else f"Entry point {key}"), source=[key.rstrip("/") if key.endswith("/") else key])
    names = {k.rstrip("/").removesuffix(".py"): v for k, v in mods.items()}
    if names:
        IMP = re.compile(r"^\s*(?:from|import)\s+\.?([A-Za-z_][\w]*)|(?:from|require\(|import\()\s*['\"](?:\.\.?/)*(?:src/)?([\w-]+)/", re.M)
        def deps(txt): return {a or b for a, b in IMP.findall(txt)} & set(names)
        for key, fs in mfiles.items():
            if key not in mods: continue
            got = set()
            for f in fs[:400]: got |= deps(rd(f, 60000))
            for d in got: M.link(mods[key], names[d], "control")
        users = {}                                          # scripts importing app code: noted, not drawn (too many wires)
        for sf, sid in scripts.items():
            for d in deps(rd(sf, 60000)): users[d] = users.get(d, 0) + 1
        for d, k in users.items(): M.nodes[names[d]]["detail"] += f" Used by {k} script(s)."
    # compose services: what runs
    for f in files:
        if not re.match(r"(docker-)?compose[\w.-]*\.ya?ml$", os.path.basename(f)) or "/" in relf[f]: continue
        txt = rd(f); body = re.search(r"^services:\s*\n(.*?)(?=^\S|\Z)", txt, re.M | re.S)
        if not body: continue
        for svc in re.findall(r"^  ([\w.-]+):\s*$", body.group(1), re.M):
            nid = M.add("d-" + svc, "service", svc, "container (docker compose)", f"Compose service {svc} in {relf[f]}", source=[relf[f]])
            block = re.search(rf"^  {re.escape(svc)}:\s*\n((?:^ {{4,}}.*\n?)*)", body.group(1), re.M)
            if block and re.search(r"^\s+build:", block.group(1), re.M):
                for key, mid in mods.items():
                    if not key.endswith("/"): M.link(nid, mid, "control")

    # ---- agents: skills in the repo, and user skills that name the repo
    skill_dirs = [os.path.join(R, d) for d in (".agents/skills", ".claude/skills", ".pi/skills", ".pi/agents", ".claude/agents", ".github/agents")]
    user_dirs = [f"{HOME}/.pi/agent/skills", f"{HOME}/.claude/skills", f"{HOME}/.agents/skills", f"{HOME}/.pi/agent/agents", f"{HOME}/.claude/agents"]
    found, cand = {}, []
    for base in skill_dirs + user_dirs:
        for p in glob.glob(f"{base}/*/SKILL.md") + glob.glob(f"{base}/*.md"):
            real = os.path.realpath(p)
            if real in (x[1] for x in cand) or os.path.realpath(R) in real and "/tests/" in real: continue
            cand.append((p, real, base in skill_dirs))
    meta = {}
    for p, real, local in cand:
        txt = rd(p); fm = re.match(r"---\n(.*?)\n---", txt, re.S); f = fm.group(1) if fm else ""
        name = (re.search(r"^name:\s*(.+)$", f, re.M) or [None, os.path.basename(os.path.dirname(p)) if p.endswith("SKILL.md") else os.path.basename(p)[:-3]])[1].strip()
        desc = re.search(r"^description:\s*(?:>-?|\|)?\s*\n?((?:.+\n?)+?)(?=^\S|\Z)", f + "\n", re.M)
        desc = " ".join(desc.group(1).split()) if desc else ""
        meta[name] = (p, txt, local, desc, (re.search(r"^model:\s*(.+)$", f, re.M) or [None, ""])[1].strip())
    for name, (p, txt, local, desc, model) in meta.items():
        if local or M.name_re.search(txt): found[name] = p
    for name in list(found):                                # skills that a found skill points at become part of it
        for other, (p, txt, *_) in meta.items():
            if other not in found and re.search(rf"(?<![\w-]){re.escape(other)}(?![\w-])", meta[name][1]) and ("/" + other + "/") in meta[name][1]:
                found.setdefault(name + "+", []); found[name + "+"].append(other)
    agent_ids = {}
    for name, p in [(n, p) for n, p in found.items() if not n.endswith("+")]:
        _, txt, local, desc, model = meta[name]
        srcs = [M.rel(os.path.realpath(p))] + [M.rel(os.path.realpath(meta[o][0])) for o in found.get(name + "+", [])]
        first = re.split(r"(?<=[.!?])\s", desc)[0] if desc else ""
        nid = M.add("a-" + name, "agent", name, first, desc, source=srcs, **({"model": model} if model else {}))
        agent_ids[name] = nid
        ext_texts[nid] = txt + "".join(meta[o][1] for o in found.get(name + "+", []))
        for o in found.get(name + "+", []):                 # scripts that live next to an included skill
            for sp in glob.glob(os.path.join(os.path.dirname(meta[o][0]), "*.py")) + glob.glob(os.path.join(os.path.dirname(meta[o][0]), "*.sh")):
                sid = M.add("s-" + os.path.basename(sp), "script", os.path.basename(sp), describe(sp), source=[M.rel(os.path.realpath(sp))])
                scripts[sp] = sid
    for a, ida in agent_ids.items():
        for b, idb in agent_ids.items():
            if a != b and re.search(rf"(?<![\w-]){re.escape(b)}(?![\w-])", ext_texts[ida]): M.link(ida, idb, "control")
    if agent_ids:
        you = M.add("you", "human", "You (maintainer)", "decisions, approvals", "The person who starts the agents and approves what ships.", source=["(human)"])
        heads = [i for i in agent_ids.values() if not any(e[1] == i for e in M.edges)] or list(agent_ids.values())
        for i in heads: M.link(you, i, "human")

    # ---- hand-over folders named by agents or timers (outside the repo)
    PATH = re.compile(r"(~|" + re.escape(HOME) + r")(/[\w.+-]+)+/?")
    for nid, txt in list(ext_texts.items()):
        if M.nodes[nid]["kind"] == "script": continue
        for m in PATH.finditer(txt):
            p = os.path.expanduser(m.group(0).rstrip("/.")); real = os.path.realpath(p)
            if real.startswith(os.path.realpath(R)) or any(real.startswith(os.path.realpath(d)) for d in user_dirs) or "/." in p[len(HOME):]: continue
            if os.path.isfile(p) and os.path.splitext(p)[1] in SCRIPT_EXT and len(p[len(HOME):].split("/")) >= 3:
                sid = M.add("s-" + tilde(p), "script", os.path.basename(p), describe(p), source=[tilde(p)])
                scripts[p] = sid; ext_texts.setdefault(sid, rd(p))
                if not NEG.search(txt[max(0, txt.rfind("\n", 0, m.start())):txt.find("\n", m.end())]): M.link(nid, sid, "control")
                continue
            if os.path.isdir(p) and p.rstrip("/") != HOME and len(p[len(HOME):].split("/")) >= 3:
                line = txt[max(0, txt.rfind("\n", 0, m.start())):txt.find("\n", m.end())]
                if NEG.search(line): continue
                fid = M.add("f-" + tilde(p), "file", os.path.basename(p) + "/", tilde(p), f"Folder {tilde(p)}, named by the agents/timers.", source=[tilde(p)], glob=tilde(p) + "/*")
                reads = re.search(r"(?i)\bread|input|from\b", line) and not re.search(r"(?i)write|leave|creat|produce|output|save", line)
                M.link(fid, nid) if reads else M.link(nid, fid)

    # ---- edges between scripts, and from outside texts to scripts
    stexts = {sid: rd(sf) for sf, sid in scripts.items()}
    for sid, txt in list(stexts.items()) + [(k, positive(v)) for k, v in ext_texts.items()]:
        for sf, other in scripts.items():
            if other != sid and re.search(r"(?<![\w-])" + re.escape(os.path.basename(sf)) + r"(?![\w-])", txt): M.link(sid, other, "control")

    # ---- generated outputs
    gens = {}
    for f in files:
        if os.path.splitext(f)[1] in {".png", ".jpg", ".blp", ".tga", ".gif", ".zip", ".ico", ".woff", ".woff2", ".pdf"}: continue
        head = rd(f, 600); m = GEN.search(head)
        if m or (NOEDIT.search(head) and not relf[f].startswith(("tools/", "scripts/"))):
            gen = os.path.basename(m.group(1)) if m else ""
            key = (os.path.dirname(relf[f]), os.path.splitext(f)[1]); gens.setdefault(key, {"files": [], "by": set()})
            gens[key]["files"].append(relf[f]); gens[key]["by"].add(gen)
    for (d, ext), g in gens.items():
        title = (d + "/" if d else "") + ("*" + ext if len(g["files"]) > 1 else os.path.basename(g["files"][0]))
        nice = "/".join(title.split("/")[-2:]) if len(title) > 26 else title
        oid = M.add("o-" + title, "output", nice, f"generated · {d or '.'}/" if len(g["files"]) > 1 else f"generated file · {d or '.'}/",
                    f"Generated, do not edit by hand: {', '.join(g['files'][:8])}", source=[os.path.join(d, "*" + ext) if len(g["files"]) > 1 else g["files"][0]])
        for gen in g["by"]:
            for sf, sid in scripts.items():
                if os.path.basename(sf) == gen: M.link(sid, oid)

    # ---- inputs: data folders the scripts read, hosts they fetch from
    gen_dirs = {d for d, _ in gens}
    data_dirs = {}
    for f in files:
        d = os.path.dirname(relf[f])
        if d and d not in gen_dirs and len(d.split("/")) <= 3 and not any(p in SKIP_DIRS for p in d.split("/")) and not d.startswith((".", "test", "tests")):
            data_dirs.setdefault(d, [0, 0]); data_dirs[d][0] += 1; data_dirs[d][1] += os.path.splitext(f)[1] in DATA_EXT
    for d, (n, k) in data_dirs.items():
        if n >= 2 and k / n >= 0.6:
            readers = [sid for sid, t in stexts.items() if d in t]
            if readers:
                iid = M.add("i-" + d, "input", d + "/", f"{n} data files", f"Data folder {d}/ read by {len(readers)} script(s).", source=[d])
                for sid in readers: M.link(iid, sid)
    GH = re.compile(r"https?://(?:www\.)?(github\.com|gitlab\.com|codeberg\.org)/([\w.-]+/[\w.-]+)")
    for sid, txt in stexts.items():
        if not FETCH.search(txt): continue
        consts = {m.group(1): m.group(2) for m in re.finditer(r"^\s*([A-Za-z_]\w*)\s*[:=]\s*[fr]?[\"'](https?://[^\"'\s]+)", txt, re.M)}
        lines = []
        for line in txt.splitlines():
            if line.lstrip().startswith(("#", "//", "*", "--")) or not FETCH.search(line): continue
            lines.append(line + " " + " ".join(u for k, u in consts.items() if re.search(rf"\b{k}\b", line)))
        for line in lines:
            for host, repo_ in GH.findall(line):
                repo_ = re.sub(r"\.git$", "", repo_)
                if repo_.split("/")[1] in ("blob", "tree", "issues"): continue
                iid = M.add("h-" + repo_, "input", repo_, f"git repo on {host}", f"Source repository https://{host}/{repo_}.", source=["url:" + host + "/" + repo_]); M.link(iid, sid)
            for host in URL.findall(line):
                if host in ("github.com", "gitlab.com", "codeberg.org", "www.github.com") or any(h in host + "/" for h in DOC_HOSTS) or TEST_HOST.search(host): continue
                iid = M.add("h-" + host, "input", host, "fetched over the network", f"External source {host}.", source=["url:" + host]); M.link(iid, sid)
        for m in re.finditer(r"git(?:@|://|\s+clone\s+https?://)([\w.-]+)[/:]([\w.-]+/[\w.-]+)", txt):
            iid = M.add("h-" + m.group(2), "input", m.group(2).replace(".git", ""), f"git repo on {m.group(1)}", "", source=["url:" + m.group(1)]); M.link(iid, sid)
    if os.path.exists(os.path.join(R, ".gitmodules")):
        for u in re.findall(r"url\s*=\s*(\S+)", rd(os.path.join(R, ".gitmodules"))):
            M.add("h-" + u, "input", u.rstrip("/").split("/")[-1].replace(".git", ""), "git submodule", u, source=[".gitmodules"])
    return M

def tidy(M, max_scripts=16):
    """Merge script families (gen_*.py) and unconnected scripts so the map stays readable."""
    linked = {x for e in M.edges for x in e[:2]}
    scripts = [n for n in M.nodes.values() if n["kind"] == "script" and n["id"].startswith("s-")]
    def merge(ids, nid, title, sub):
        keep = M.add(nid, "script", title, sub, f"{len(ids)} scripts: " + ", ".join(M.nodes[i]["title"] for i in ids),
                     source=sorted({s for i in ids for s in M.nodes[i]["source"]}))
        for i in ids:
            if i == keep: continue
            M.edges = {(keep if a == i else a, keep if b == i else b, k) for a, b, k in M.edges}
            del M.nodes[i]
        M.edges = {e for e in M.edges if e[0] != e[1]}
    subs = {}
    for n in scripts:
        parts = n["source"][0].split("/")
        if len(parts) == 3 and parts[0] in SCRIPT_DIRS: subs.setdefault("/".join(parts[:2]), []).append(n["id"])
    for d, ids in subs.items():
        if len(ids) >= 3: merge(ids, f"s-{d}/", f"{d.split('/')[-1]}/ ({len(ids)})", f"scripts in {d}/")
    scripts = [n for n in M.nodes.values() if n["kind"] == "script" and n["id"].startswith("s-")]
    if len(scripts) > max_scripts:
        fam = {}
        for n in scripts:
            m = re.match(r"([a-z]+[_-])", n["title"])
            if m: fam.setdefault((os.path.dirname(n["source"][0]), m.group(1), os.path.splitext(n["title"])[1]), []).append(n["id"])
        for (d, pre, ext), ids in fam.items():
            if len(ids) >= 3: merge(ids, f"s-{d}/{pre}*", f"{pre}*{ext} ({len(ids)})", f"{d or '.'}/{pre}*{ext}")
    linked = {x for e in M.edges for x in e[:2]}
    loose = [n["id"] for n in M.nodes.values() if n["kind"] == "script" and n["id"] not in linked and n["id"].startswith("s-")]
    if len([n for n in M.nodes.values() if n["kind"] == "script"]) > max_scripts and len(loose) >= 3:
        merge(loose, "s-other", f"other tools ({len(loose)})", "scripts with no detected links")
    ci = [n["id"] for n in M.nodes.values() if n["id"].startswith("ci-") and not any(n["id"] in e[:2] for e in M.edges)]
    if len([n for n in M.nodes.values() if n["id"].startswith("ci-")]) > 6 and len(ci) >= 3:
        keep = M.add("ci-checks", "service", f"CI checks ({len(ci)})", "workflows with no detected links",
                     "Workflows: " + ", ".join(M.nodes[i]["title"] for i in ci), source=sorted({x for i in ci for x in M.nodes[i]["source"]}))
        for i in ci: del M.nodes[i]
    rest = [n for n in M.nodes.values() if n["kind"] == "script" and n["id"] != "s-other"]
    if len(rest) > max_scripts:
        deg = {}
        for a, b, _ in M.edges: deg[a] = deg.get(a, 0) + 1; deg[b] = deg.get(b, 0) + 1
        rest.sort(key=lambda n: (-deg.get(n["id"], 0), n["title"]))
        extra = [n["id"] for n in rest[max_scripts:]] + (["s-other"] if "s-other" in M.nodes else [])
        count = sum(len(M.nodes[i]["source"]) for i in extra)
        M.edges = {e for e in M.edges if e[0] not in extra or e[1] not in extra}
        merge(extra, "s-more", f"more scripts ({count})", "less connected scripts")
        M.edges = {e for e in M.edges if "s-more" not in e[:2] or e[2] != "control" or M.nodes[e[0] if e[1] == "s-more" else e[1]]["kind"] != "script"}

COLS = [("input", "Sources"), ("service", "Services, timers & CI"), ("script", "Scripts"), ("module", "App code"), ("agent", "Agents & hand-overs"), ("output", "Outputs")]
def layout(M):
    """Columns by kind, rows ordered by the average row of each node's neighbours (fewer crossings), pitch 6 units."""
    colof = {"input": 0, "service": 1, "script": 2, "module": 3, "agent": 4, "human": 4, "file": 4, "output": 5}
    used = sorted({colof[n["kind"]] for n in M.nodes.values()})
    cols = {c: [n for n in M.nodes.values() if colof[n["kind"]] == c] for c in used}
    for c, ns in cols.items():
        ns.sort(key=lambda n: (n["kind"] != "human", n["kind"] == "file", n["title"].lower()))
        for i, n in enumerate(ns): n["_r"] = i
    nb = {n: [] for n in M.nodes}
    for a, b, _ in M.edges: nb[a].append(b); nb[b].append(a)
    for _ in range(8):
        for c, ns in cols.items():
            for n in ns:
                o = [M.nodes[x]["_r"] for x in nb[n["id"]] if colof[M.nodes[x]["kind"]] != c]
                n["_k"] = (sum(o) / len(o)) if o else n["_r"]
                if n["kind"] == "human": n["_k"] = -1
            ns.sort(key=lambda n: n["_k"])
            for i, n in enumerate(ns): n["_r"] = i
    x, H = 0, 8                                             # wrap columns taller than 8 boxes into sub-columns
    for c in used:
        ns = sorted(cols[c], key=lambda n: n["_r"]); per = -(-len(ns) // -(-len(ns) // H))
        for i, n in enumerate(ns):
            n["x"], n["y"] = x + (i // per) * 13, 4 + (i % per) * 6; n.pop("_r"); n.pop("_k", None)
        x += (-(-len(ns) // per) - 1) * 13 + 21
    groups = []
    for c in used:
        label = COLS[c][1] if c != 4 else ("Agents & hand-overs" if any(n["kind"] == "file" for n in cols[c]) else "Agents")
        groups.append({"label": label, "nodes": [n["id"] for n in cols[c] if n["kind"] != "human"], "kind": COLS[c][0]})
    return [g for g in groups if g["nodes"]]

def live_section(M):
    L = {"match": M.name, "working_seconds": 60}
    ag = [n for n in M.nodes.values() if n["kind"] == "agent"]
    if ag: L["sessions"] = [{"node": n["id"], "match": re.escape(n["title"])} for n in ag]
    fs = [{"node": n["id"], "glob": n["glob"]} for n in M.nodes.values() if n.get("glob")]
    if fs: L["files"] = fs
    us = [{"node": n["id"], "unit": n["unit"]} for n in M.nodes.values() if n.get("unit")]
    if us: L["units"] = us
    if os.path.isdir(os.path.join(M.repo, ".git")):
        pr = next((n["id"] for n in M.nodes.values() if n["kind"] == "output"), None)
        if pr: L["git"] = [{"node": pr, "repo": tilde(M.repo), "exclude": ["main", "master"]}]
    return L

def draft(repo):
    M = scan(repo); tidy(M); groups = layout(M)
    nodes = []
    for n in M.nodes.values():
        n = {k: v for k, v in n.items() if k not in ("glob", "unit")}
        nodes.append(n)
    return {"version": FORMAT_VERSION, "title": M.name, "subtitle": f"draft from discover.py · {len(nodes)} parts found",
            "repo": tilde(M.repo), "nodes": nodes, "edges": sorted([list(e) for e in M.edges]), "groups": groups, "live": live_section(M)}

