def covered(src, srcs):
    return any(src == s or fnmatch.fnmatch(src, s) or (s.endswith("/*") and src.startswith(s[:-1])) for s in srcs)
def exists(repo, s):
    if s.startswith(("(", "url:", "cron:")): return True
    if s.startswith("systemd:"): return bool(sh("systemctl", "--user", "cat", s[8:] + ".timer"))
    p = os.path.expanduser(s) if s.startswith("~") else os.path.join(repo, s)
    return bool(glob.glob(p)) or os.path.exists(p)
def drift(m, fresh=None):
    """Compare a map's `source` fields with the repo. Returns {"stale": [...], "new": [...]}."""
    repo = os.path.expanduser(m.get("repo", ""))
    if not repo or not os.path.isdir(repo): return {"stale": [], "new": [], "error": "map has no valid `repo`"}
    fresh = fresh or draft(repo)
    have = [s for n in m["nodes"] for s in n.get("source", [])] + m.get("ignore", [])
    stale = [n["id"] for n in m["nodes"] if n.get("source") and not any(exists(repo, s) for s in n["source"])]
    titles = {n["title"].lower() for n in m["nodes"]} | {n["id"] for n in m["nodes"]}
    new, extra = [], []
    for n in fresh["nodes"]:
        miss = [s for s in n["source"] if not covered(s, have)]
        if not miss: continue
        if n["title"].lower() in titles or n["id"] in titles:
            if len(n["source"]) > 1: extra += [f"{s} (part of {n['title']})" for s in miss]   # a merged box gained a file
        else: new.append(n)
    return {"stale": stale, "new": [f"{n['title']} ({', '.join(n['source'][:2])})" for n in new] + extra, "new_nodes": new, "new_sources": extra}

def update(m, repo):
    """Add new parts to an existing map next to nodes of the same kind; never move or delete what is there."""
    fresh = draft(repo); d = drift(m, fresh)
    ids = {n["id"] for n in m["nodes"]}
    def box(n): return (n["x"], n["y"], n["x"] + 11, n["y"] + 4)
    taken = [box(n) for n in m["nodes"] if "x" in n]
    added = []
    for n in d["new_nodes"]:
        same = [o for o in m["nodes"] if o["kind"] == n["kind"] and "x" in o]
        x = round(sum(o["x"] for o in same) / len(same)) if same else max([o.get("x", 0) for o in m["nodes"]] + [0]) + 18
        y = max([o["y"] for o in same] + [0]) + 6
        while any(not (x + 12 <= a or a + 12 <= x or y + 5 <= b or b2 + 1 <= y) for a, b, a2, b2 in taken): y += 6
        n = {**n, "x": x, "y": y, "new": True}; n["id"] = n["id"] if n["id"] not in ids else n["id"] + "-new"
        taken.append(box(n)); m["nodes"].append(n); ids.add(n["id"]); added.append(n["id"])
    for a, b, k in fresh["edges"]:
        if (a in added or b in added) and a in ids and b in ids and [a, b, k] not in m["edges"]: m["edges"].append([a, b, k])
    for n in m["nodes"]:
        if n["id"] in d["stale"]: n["stale"] = True
        elif n.pop("stale", None): pass
    return m, added, d["stale"]

