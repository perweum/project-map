"""Tests: build a small fake repository, discover it, render it, check drift and the board.
Run: python3 -m unittest discover -s tests -v"""
import json, os, shutil, subprocess, sys, tempfile, unittest

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
import discover, board  # noqa: E402

def write(root, path, text, exe=False):
    p = os.path.join(root, path); os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f: f.write(text)
    if exe: os.chmod(p, 0o755)

class Fixture(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.mkdtemp(prefix="pmfix-")
        cls.repo = os.path.join(cls.tmp, "widget-factory")
        r = cls.repo
        write(r, "tools/gen_data.py", '"""Build out/*.lua from data/input."""\nopen("data/input/a.csv")\n# writes out/\n', True)
        write(r, "tools/fetch.py", '"""Download the price list."""\nimport urllib.request\nURL = "https://api.opendata.net/prices"\nurllib.request.urlopen(URL)\n', True)
        write(r, "tools/release.sh", "#!/bin/sh\n# Package and publish a release.\npython3 tools/gen_data.py\n", True)
        for k in "abc": write(r, f"tools/extra/{k}_tool.py", f'"""Extra tool {k}."""\nopen("data/input/a.csv")\n', True)
        write(r, "data/input/a.csv", "a,b\n1,2\n"); write(r, "data/input/b.csv", "a,b\n3,4\n")
        write(r, "out/one.lua", "-- GENERATED by tools/gen_data.py. Do not edit.\nreturn {}\n")
        write(r, "out/two.lua", "-- GENERATED by tools/gen_data.py. Do not edit.\nreturn {}\n")
        write(r, "src/__init__.py", '"""Core widget logic."""\n'); write(r, "src/a.py", "from src import b\n"); write(r, "src/b.py", "x = 1\n")
        write(r, "app.py", "import src\nif __name__ == '__main__':\n    pass\n")
        write(r, "package.json", json.dumps({"scripts": {"build": "python3 tools/gen_data.py", "lint": "eslint ."}}))
        write(r, ".github/workflows/ci.yml", "name: CI\non: [push, pull_request]\njobs:\n  t:\n    steps:\n      - run: python3 tools/gen_data.py\n")
        write(r, ".github/workflows/release.yml", "name: Release\non:\n  push:\n    tags: ['v*']\njobs:\n  r:\n    steps:\n      - run: sh tools/release.sh\n")
        write(r, ".agents/skills/widget-builder/SKILL.md", "---\nname: widget-builder\ndescription: Builds widgets. Hands work to widget-checker.\n---\nRun tools/gen_data.py. Never run tools/release.sh.\n")
        write(r, ".agents/skills/widget-checker/SKILL.md", "---\nname: widget-checker\ndescription: Checks the work.\nmodel: some-model\n---\nRead the diff.\n")
        subprocess.run(["git", "init", "-q", r]); subprocess.run(["git", "-C", r, "add", "-A"])
        cls.map = discover.draft(r)
        cls.ids = {n["id"]: n for n in cls.map["nodes"]}
        cls.edges = {tuple(e) for e in cls.map["edges"]}

    @classmethod
    def tearDownClass(cls): shutil.rmtree(cls.tmp)

    def kind(self, k): return {n["title"] for n in self.map["nodes"] if n["kind"] == k}
    def node(self, title): return next(n["id"] for n in self.map["nodes"] if n["title"] == title)

    def test_finds_parts(self):
        self.assertTrue({"gen_data.py", "fetch.py", "release.sh", "npm scripts"} <= self.kind("script"))
        self.assertTrue({"CI", "Release"} <= self.kind("service"))
        self.assertTrue({"widget-builder", "widget-checker"} <= self.kind("agent"))
        self.assertIn("You (maintainer)", self.kind("human"))
        self.assertTrue({"src/", "app.py"} <= self.kind("module"))
        self.assertTrue({"data/input/", "api.opendata.net"} <= self.kind("input"))
        self.assertTrue({"out/*.lua", "Published release"} <= self.kind("output"))

    def test_links(self):
        n = self.node
        for e in [(n("CI"), n("gen_data.py"), "control"), (n("gen_data.py"), n("out/*.lua"), "data"),
                  (n("data/input/"), n("gen_data.py"), "data"), (n("api.opendata.net"), n("fetch.py"), "data"),
                  (n("app.py"), n("src/"), "control"), (n("widget-builder"), n("widget-checker"), "control"),
                  (n("npm scripts"), n("gen_data.py"), "control"), (n("Release"), n("Published release"), "data"),
                  (n("You (maintainer)"), n("widget-builder"), "human")]:
            self.assertIn(e, self.edges)
        self.assertNotIn((n("widget-builder"), n("release.sh"), "control"), self.edges, "a 'never run' line is not a link")

    def test_version(self):
        self.assertEqual(self.map["version"], 1)
        d = os.path.join(self.tmp, "maps", "ver"); os.makedirs(d, exist_ok=True)
        future = {"version": 2, "title": "x", "nodes": [{"id": "a", "x": 0, "y": 0, "kind": "script", "title": "A"}], "edges": []}
        json.dump(future, open(os.path.join(d, "map.json"), "w"))
        r = subprocess.run([sys.executable, "-I", "-B", os.path.join(HERE, "render_map.py"), os.path.join(d, "map.json")], capture_output=True, text=True)
        self.assertNotEqual(r.returncode, 0); self.assertIn("version 2", r.stderr)

    def test_inner_maps(self):
        extra = next(n for n in self.map["nodes"] if n["title"].startswith("extra/"))
        inside = [m for m in extra["inner"]["nodes"] if not m.get("outside")]
        self.assertEqual(sorted(m["title"] for m in inside), ["a_tool.py", "b_tool.py", "c_tool.py"])
        outside = [m["title"] for m in extra["inner"]["nodes"] if m.get("outside")]
        self.assertIn("data/input/", outside, "a merged box shows what its members read")
        self.assertTrue(any(e[0] == self.node("data/input/") for e in extra["inner"]["edges"]))
        src = self.ids[self.node("src/")]["inner"]
        t = {m["id"]: m["title"] for m in src["nodes"]}
        self.assertIn(["a.py", "b.py"], [[t[a], t[b]] for a, b, _ in src["edges"]], "src/a.py imports src/b.py")
        d = os.path.join(self.tmp, "maps", "inner"); os.makedirs(d, exist_ok=True)
        bad = {"title": "x", "nodes": [{"id": "a", "x": 0, "y": 0, "kind": "script", "title": "A",
               "inner": {"nodes": [{"id": "b", "kind": "robot", "title": "B"}], "edges": [["b", "zz"]]}}], "edges": []}
        json.dump(bad, open(os.path.join(d, "map.json"), "w"))
        r = subprocess.run([sys.executable, "-I", "-B", os.path.join(HERE, "render_map.py"), os.path.join(d, "map.json")], capture_output=True, text=True)
        self.assertNotEqual(r.returncode, 0); self.assertIn("inner", r.stderr); self.assertIn("robot", r.stderr)

    def test_model_and_layout(self):
        self.assertEqual(self.ids[self.node("widget-checker")]["model"], "some-model")
        boxes = [(n["x"], n["y"]) for n in self.map["nodes"]]
        self.assertEqual(len(boxes), len(set(boxes)), "no two boxes on the same spot")

    def test_render_and_validate(self):
        d = os.path.join(self.tmp, "maps", "widget"); os.makedirs(d, exist_ok=True)
        m = dict(self.map); m.pop("repo")
        json.dump(m, open(os.path.join(d, "map.json"), "w"))
        r = subprocess.run([sys.executable, "-I", "-B", os.path.join(HERE, "render_map.py"), os.path.join(d, "map.json")], capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        html = open(os.path.join(d, "map.html")).read()
        self.assertIn('"widget-builder"', html); self.assertNotIn("/*MAP_DATA*/null", html)
        self.assertIn('id="search"', html); self.assertIn('id="tools"', html); self.assertIn('id="drawer"', html); self.assertIn("function trace(", html)
        bad = {"title": "x", "nodes": [{"id": "a", "x": 0, "y": 0, "kind": "robot", "title": "A"}], "edges": [["a", "zz"]]}
        json.dump(bad, open(os.path.join(d, "bad.json"), "w"))
        r = subprocess.run([sys.executable, "-I", "-B", os.path.join(HERE, "render_map.py"), os.path.join(d, "bad.json"), "--out", os.path.join(d, "bad.html")], capture_output=True, text=True)
        self.assertNotEqual(r.returncode, 0); self.assertIn("robot", r.stderr); self.assertIn("zz", r.stderr)
        self.assertFalse(os.path.exists(os.path.join(d, "bad.html")))

    def test_drift(self):
        m = json.loads(json.dumps(self.map))
        self.assertEqual(discover.drift(m)["stale"] + discover.drift(m)["new"], [])
        write(self.repo, "tools/brand_new.py", '"""New."""\nimport tools.gen_data\n# gen_data.py\n', True)
        os.rename(os.path.join(self.repo, "tools/fetch.py"), os.path.join(self.tmp, "fetch.py"))
        subprocess.run(["git", "-C", self.repo, "add", "-A"])
        try:
            d = discover.drift(m)
            self.assertIn(self.node("fetch.py"), d["stale"])
            self.assertTrue(any("brand_new.py" in x for x in d["new"]), d["new"])
            m2, added, stale = discover.update(json.loads(json.dumps(m)), self.repo)
            self.assertTrue(added and stale)
            self.assertEqual(len({(n["x"], n["y"]) for n in m2["nodes"]}), len(m2["nodes"]))
        finally:
            os.remove(os.path.join(self.repo, "tools/brand_new.py"))
            os.rename(os.path.join(self.tmp, "fetch.py"), os.path.join(self.repo, "tools/fetch.py"))
            subprocess.run(["git", "-C", self.repo, "add", "-A"])

    def test_board_status(self):
        m = {"title": "w", "nodes": [{"id": "q", "x": 0, "y": 0, "kind": "file", "title": "queue"}], "edges": [],
             "live": {"files": [{"node": "q", "glob": os.path.join(self.repo, "data/input/*.csv"), "alert": True}]}}
        old = __import__("time").time() - 3600
        for f in ("a.csv", "b.csv"): os.utime(os.path.join(self.repo, "data/input", f), (old, old))
        s = board.status(m)
        self.assertEqual(s["nodes"]["q"]["status"], "waiting")
        self.assertIn("2", s["nodes"]["q"]["line"])

    def test_redaction(self):
        self.assertNotIn("abc123secretvalue", board.red("export API_TOKEN=abc123secretvalue && run"))
        self.assertNotIn("AKIAABCDEFGHIJKLMNOP", board.red("key AKIAABCDEFGHIJKLMNOP"))

if __name__ == "__main__":
    unittest.main()
